    'AI advisory output. Not an execution instruction. reasoning_summary is user-facing only.';
COMMENT ON COLUMN bjstock.ai_advice_results.raw_response IS
    'Serialized TEXT. Do not treat chain-of-thought as a required stored field.';
COMMENT ON COLUMN bjstock.ai_advice_results.used_in_decision IS
    'Whether this advice was recorded alongside the decision. AI still does not place orders.';

CREATE INDEX idx_ai_advice_results_request_id
    ON bjstock.ai_advice_results (request_id);
