CREATE TABLE bjstock.orders (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_order_id     TEXT NOT NULL,
    strategy_run_id     BIGINT NOT NULL,
    instrument_id       BIGINT NOT NULL,
    evaluation_id       BIGINT,
    side                TEXT NOT NULL,
    order_type          TEXT NOT NULL,
    requested_price     NUMERIC(18, 4),
    quantity            NUMERIC(20, 4) NOT NULL,
    status              TEXT NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    executed_at         TIMESTAMPTZ,
    cancelled_at        TIMESTAMPTZ,
    CONSTRAINT uq_orders_client_order_id UNIQUE (client_order_id),
    CONSTRAINT fk_orders_run
        FOREIGN KEY (strategy_run_id)
        REFERENCES bjstock.strategy_runs (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_orders_instrument
        FOREIGN KEY (instrument_id)
        REFERENCES bjstock.instruments (id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_orders_evaluation
        FOREIGN KEY (evaluation_id)
        REFERENCES bjstock.stock_evaluations (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_orders_client_order_id_not_empty CHECK (client_order_id <> ''),
    CONSTRAINT ck_orders_side CHECK (side IN ('BUY', 'SELL')),
    CONSTRAINT ck_orders_order_type CHECK (order_type IN ('MARKET', 'LIMIT')),
    CONSTRAINT ck_orders_requested_price_nonneg
        CHECK (requested_price IS NULL OR requested_price >= 0),
    CONSTRAINT ck_orders_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_orders_status
        CHECK (status IN ('CREATED', 'VIRTUAL_FILLED', 'CANCELLED', 'REJECTED'))
);

COMMENT ON TABLE bjstock.orders IS
    'Virtual orders for paper trading. evaluation_id is nullable to allow future manual virtual orders.';
COMMENT ON COLUMN bjstock.orders.client_order_id IS
    'Portable UUID string (TEXT), not PostgreSQL UUID type.';

CREATE INDEX idx_orders_run_created
    ON bjstock.orders (strategy_run_id, created_at DESC);

CREATE INDEX idx_orders_instrument_created
    ON bjstock.orders (instrument_id, created_at DESC);

